import { act, cleanup, fireEvent, render, screen, waitFor } from '@testing-library/react';
import { afterEach, expect, it, vi } from 'vitest';
import { createLocalSystem } from '@tuxos/system';
import { learnLinux } from '@tuxos/module-learn-linux';
import { exploration } from '@tuxos/module-exploration';
import LearningHub from './LearningHub';
import LearningTerminal from './LearningTerminal';
vi.mock('@tuxos/module-terminal/view', () => ({ TerminalSurface: ({ learningModule }: { learningModule?: string }) => <div data-testid="terminal-surface">{learningModule}</div> }));
afterEach(cleanup);
it('keeps the journal separate, reuses its dedicated terminal and updates from learning commands', async () => {
  const system = createLocalSystem({ storage: { get: async () => null, set: async () => {}, remove: async () => {} }, modules: [learnLinux, exploration].map(m => ({ manifest: m.manifest, load: async () => m })) });
  await system.boot('ada');
  const result = await system.openApp('learn-linux');
  if (!result.ok) throw new Error(result.error.message);
  const view = render(<LearningHub system={system} windowId={result.value} />);
  await screen.findByText('Learn Linux, one step at a time.');
  expect(screen.queryByTestId('terminal-surface')).toBeNull();
  expect(screen.queryByText('Focus view')).toBeNull();
  fireEvent.click(screen.getByRole('button', { name: 'Open Terminal' }));
  await waitFor(async () => expect((await system.session()).windows.filter(w => w.appId === 'learn-linux-terminal')).toHaveLength(1));
  fireEvent.click(screen.getByRole('button', { name: 'Open Terminal' }));
  await act(async () => { await Promise.resolve(); });
  expect((await system.session()).windows.filter(w => w.appId === 'learn-linux-terminal')).toHaveLength(1);
  fireEvent.click(screen.getByRole('button', { name: /Let’s begin/ }));
  await screen.findByLabelText('Current Linux mission');
  const shell = await system.createTerminal({ learningModule: 'learn-linux' });
  await act(async () => { await shell.run('whoami'); });
  await waitFor(() => expect(screen.getByText(/Step 2 of 3/)).toBeTruthy());
  fireEvent.click(screen.getByRole('tab', { name: 'Play' }));
  await screen.findByText('Play and explore');
  expect((await system.session()).windows.some(w => w.appId === 'play')).toBe(false);
  fireEvent.click(screen.getByRole('tab', { name: 'Linux course' }));
  await screen.findByText(/Step 2 of 3/);
  view.unmount();
  render(<LearningTerminal system={system} windowId="practice" />);
  expect(screen.getByTestId('terminal-surface').textContent).toBe('learn-linux');
  cleanup(); await system.reset();
});
